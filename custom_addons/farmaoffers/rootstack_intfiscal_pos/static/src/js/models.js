odoo.define('rootstack_intfiscal_pos.models', function (require) {
    let models = require('point_of_sale.models');
    let utils = require('web.utils');

    var round_di = utils.round_decimals;
    var round_pr = utils.round_precision;

    /* add field invoicing_mode to res.company */
    models.load_fields('res.company', ['invoicing_mode']);
    /* add fields of partner to support electronic invoice */
    models.load_fields('res.partner', ['business_name', 'l10n_pa_dv', 'ei_client_type', 'ei_taxpayer_type', 'ei_identification_type', 'ei_location_province_id', 'ei_location_district_id', 'ei_location_corregimiento_id'])
    /* load master data of locations for electronic invoice */
    models.load_models([
        {
            model: 'ebi.location.province',
            fields: ['code', 'name'],
            loaded: function (self, data) {
                self.ebiLocationProvince = data
            }
        },
        {
            model: 'ebi.location.district',
            fields: ['code', 'name'],
            loaded: function (self, data) {
                self.ebiLocationDistrict = data
            }
        },
        {
            model: 'ebi.location.corregimiento',
            fields: ['code', 'name'],
            loaded: function (self, data) {
                self.ebiLocationCorregimiento = data
            }
        },
        {
            model: 'account.journal',
            fields: ['ei_document_type'],
            domain: function (self) { return [['id', '=', self.config.invoice_journal_id[0]]]; },
            loaded: function (self, data) {
                self.invoiceJournal = data[0]
            }
        }
    ]);


    var posModelSuper = models.PosModel.prototype;
    models.PosModel = models.PosModel.extend({
        push_and_invoice_order: function (order) {
            var self = this;
            var invoiced = new Promise(function (resolveInvoiced, rejectInvoiced) {
                if (!order.get_client()) {
                    rejectInvoiced({ code: 400, message: 'Missing Customer', data: {} });
                }
                else {
                    var order_id = self.db.add_order(order.export_as_JSON());

                    self.flush_mutex.exec(function () {
                        var done = new Promise(function (resolveDone, rejectDone) {
                            // send the order to the server
                            // we have a 30 seconds timeout on this push.
                            // FIXME: if the server takes more than 30 seconds to accept the order,
                            // the client will believe it wasn't successfully sent, and very bad
                            // things will happen as a duplicate will be sent next time
                            // so we must make sure the server detects and ignores duplicated orders

                            var transfer = self._flush_orders([self.db.get_order(order_id)], { timeout: 30000, to_invoice: true });

                            transfer.catch(function (error) {
                                rejectInvoiced(error);
                                rejectDone();
                            });

                            // on success, get the order id generated by the server
                            transfer.then(function (order_server_id) {
                                // generate the pdf and download it
                                if (order_server_id.length) {
                                    if (self.invoiceJournal.ei_document_type) {
                                        resolveInvoiced(order_server_id);
                                        return resolveDone();
                                    }
                                    self.do_action('point_of_sale.pos_invoice_report', {
                                        additional_context: {
                                            active_ids: order_server_id,
                                        }
                                    }).then(function () {
                                        resolveInvoiced(order_server_id);
                                        resolveDone();
                                    }).guardedCatch(function (error) {
                                        rejectInvoiced({ code: 401, message: 'Backend Invoice', data: { order: order } });
                                        rejectDone();
                                    });
                                } else if (order_server_id.length) {
                                    resolveInvoiced(order_server_id);
                                    resolveDone();
                                } else {
                                    // The order has been pushed separately in batch when
                                    // the connection came back.
                                    // The user has to go to the backend to print the invoice
                                    rejectInvoiced({ code: 401, message: 'Backend Invoice', data: { order: order } });
                                    rejectDone();
                                }
                            });
                            return done;
                        });
                    });
                }
            });

            return invoiced;
        },
        _save_to_server: async function (orders, options) {
            try {
                const data_orders = await posModelSuper._save_to_server.apply(this, arguments);
                this.pos_order_ids = data_orders;
                return Promise.resolve(data_orders)
            } catch (e) {
                return Promise.reject(e);
            }
        }
    });

    var OrderSuper = models.Order.prototype;
    models.Order = models.Order.extend({

        get_unit_price_discount_amount: function () {
            return this.get_unit_price() * (this.get_discount() / 100.0);
        },

        get_unit_price_with_discount: function () {
            return this.get_unit_price()  - round_di(this.get_unit_price_discount_amount(), this.pos.currency.decimals);
        },

        get_total_discount: function() {
            var result = round_pr(this.orderlines.reduce((function(sum, orderLine) {
                sum += ((orderLine.get_unit_price() - orderLine.get_unit_price_with_discount()) * orderLine.get_quantity());
                if (orderLine.display_discount_policy() === 'without_discount'){
                    sum += ((orderLine.get_lst_price() - orderLine.get_unit_price()) * orderLine.get_quantity());
                }
                return sum;
            }), 0), this.pos.currency.rounding);
            return result
        },

    });
    
    var OrderlineSuper = models.Orderline.prototype;
    models.Orderline = models.Orderline.extend({
        /**
         * calculate unit discount price
         */
        get_unit_price_discount_amount: function () {
            return this.get_unit_price() * (this.get_discount() / 100.0);
        },

        /**
         * function that calculates the unit price with the discount applied with 
         * Example: 2.22 with 25% discount rounded to two decimals places
         * formula: 2.22 - (2.22 * (25 / 100.0))
         *          2.22 - 0.56
         * price_unit = 1.66
         */
        get_unit_price_with_discount: function () {
            return this.get_unit_price()  - round_di(this.get_unit_price_discount_amount(), this.pos.currency.decimals);
        },

        /**
         * calculate total discount amount
         */
        get_discount_amount: function () {
            return this.get_unit_price_discount_amount() * this.get_quantity();
        },

        /**
         * Override function to modify the calculation of the price_unit 
         */
        get_all_prices: function () {
            if (!this.pos.invoiceJournal.ei_document_type) {
                return OrderlineSuper.get_all_prices.apply(this, arguments);
            }
            var self = this;

            var price_unit = this.get_unit_price_with_discount(); // this sentence was changed
            var taxtotal = 0;

            var product = this.get_product();
            var taxes = this.pos.taxes;
            var taxes_ids = _.filter(product.taxes_id, t => t in this.pos.taxes_by_id);
            var taxdetail = {};
            var product_taxes = [];

            _(taxes_ids).each(function (el) {
                var tax = _.detect(taxes, function (t) {
                    return t.id === el;
                });
                product_taxes.push.apply(product_taxes, self._map_tax_fiscal_position(tax, self.order));
            });
            product_taxes = _.uniq(product_taxes, function (tax) { return tax.id; });

            var all_taxes = this.compute_all(product_taxes, price_unit, this.get_quantity(), this.pos.currency.rounding);
            var all_taxes_before_discount = this.compute_all(product_taxes, this.get_unit_price(), this.get_quantity(), this.pos.currency.rounding);
            _(all_taxes.taxes).each(function (tax) {
                taxtotal += tax.amount;
                taxdetail[tax.id] = tax.amount;
            });

            return {
                "priceWithTax": all_taxes.total_included,
                "priceWithoutTax": all_taxes.total_excluded,
                "priceSumTaxVoid": all_taxes.total_void,
                "priceWithTaxBeforeDiscount": all_taxes_before_discount.total_included,
                "tax": taxtotal,
                "taxDetails": taxdetail,
            };
        },

        /**
         * Override function to replace price_unit by get_unit_price_with_discount
         */
        get_base_price: function () {
            if (!this.pos.invoiceJournal.ei_document_type) {
                return OrderlineSuper.get_base_price.apply(this, arguments);
            }
            var rounding = this.pos.currency.rounding;
            return round_pr(this.get_unit_price_with_discount() * this.get_quantity(), rounding);
        },

        /**
         * Override function to add discount_amount to show in receipt
         */
        export_for_printing: function () {
            let data = OrderlineSuper.export_for_printing.apply(this, arguments);
            var rounding = this.pos.currency.rounding;
            if (this.pos.invoiceJournal.ei_document_type) {
                data.discount_amount =  round_pr(data.price - data.price_display_one ,rounding) * data.quantity
            }
            return data;
        }
    });
});